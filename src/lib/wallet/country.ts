const BY_CODE = new Map<string, Country>(COUNTRIES.map((c) => [c.code, c]))

/** Is `value` a known ISO 3166-1 alpha-2 code (case-insensitive)? */
export function isCountryCode(value: unknown): value is string {
  return typeof value === 'string' && BY_CODE.has(value.trim().toUpperCase())
}

/** Coerce arbitrary input to a known uppercase country code, or null. */
export function sanitizeCountry(value: unknown): string | null {
  if (typeof value !== 'string') return null
  const code = value.trim().toUpperCase()
  return BY_CODE.has(code) ? code : null
}

/**
 * The emoji flag for a 2-letter country code, built from Unicode regional
 * indicator symbols. Returns '' for an unknown / malformed code.
 *
 * Note: most platforms render these as flags; a few (notably Windows in some
 * browsers) fall back to the two letters. That's an acceptable, graceful
 * degradation for a cosmetic field.
 */
export function countryFlag(code: string | null | undefined): string {
  if (!code) return ''
  const cc = code.trim().toUpperCase()
  if (!/^[A-Z]{2}$/.test(cc)) return ''
  const base = 0x1f1e6 // regional indicator 'A'
  return String.fromCodePoint(base + (cc.charCodeAt(0) - 65), base + (cc.charCodeAt(1) - 65))
}

/** Readable country name for a code, or '' if unknown. */
export function countryName(code: string | null | undefined): string {
  if (!code) return ''
  return BY_CODE.get(code.trim().toUpperCase())?.name ?? ''
}

/** Filter the country list by a free-text query (matches name or code). */
export function searchCountries(query: string): Country[] {
  const q = query.trim().toLowerCase()
  if (!q) return COUNTRIES
  return COUNTRIES.filter(
    (c) => c.name.toLowerCase().includes(q) || c.code.toLowerCase().startsWith(q),
  )
}
