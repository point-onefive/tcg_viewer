// Country "flag you represent" - an optional, self-declared country shown as an
// emoji flag next to a player's name (profile pic + username + flag). Purely
// cosmetic / for flavor; never required and never gates sign-up.
//
// We store the ISO 3166-1 alpha-2 code (uppercase, e.g. "US") rather than the
// raw emoji. The code is deterministic, lets us derive both the flag emoji and
// the readable name, and is searchable by text. The flag emoji is produced from
// the two letters via Unicode regional-indicator symbols.
//
// Framework-free so it can be imported on both server and client.

export interface Country {
  /** ISO 3166-1 alpha-2 code, uppercase. */
  code: string
  /** English country name (used for text search + readable label). */
  name: string
}

